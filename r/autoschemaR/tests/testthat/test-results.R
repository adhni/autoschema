test_that("results reopen after relocation and metadata is independent", {
  output <- new_output()
  result <- convert_dataframe(fixture(), output)
  moved <- new_output()
  expect_true(file.rename(output, moved))
  reopened <- load_result(file.path(moved, "schema.json"))
  expect_equal(summary(reopened), summary(result))
  expect_same_rows(read_table(reopened), fixture())
  copy <- summary(reopened); copy$engine <- "bad"; copy$table_rows <- list()
  expect_identical(summary(reopened)$engine, "sqlite")
  expect_true("records" %in% names(summary(reopened)$table_rows))
})

test_that("queries bind parameters and cannot write", {
  result <- convert_dataframe(fixture(), new_output())
  positional <- query(result, "SELECT row_id FROM dataset WHERE customer_id = ? ORDER BY row_id", list("A"))
  named <- query(result, "SELECT row_id FROM dataset WHERE customer_id = :customer ORDER BY row_id", list(customer = "A"))
  expect_identical(positional, named)
  expect_identical(positional$row_id, seq(1L, 12L, by = 2L))
  expect_error(query(result, "DELETE FROM records"), "readonly|read-only")
  expect_error(read_table(result, "missing"), "Unknown")
  expect_error(query(result, ""), "nonempty")
  expect_error(read_table(list()), "autoschema_result")
})

test_that("corrupt summaries and missing databases are rejected", {
  result <- convert_dataframe(fixture(), new_output())
  path <- file.path(result$output_dir, "schema.json")
  original <- readLines(path, encoding = "UTF-8")
  for (bad in c("{}", "[]", '{"engine":"duckdb"}', 'not json')) {
    writeLines(bad, path)
    expect_error(load_result(result$output_dir), class = "autoschema_invalid_result")
  }
  writeLines(original, path)
  report <- jsonlite::read_json(path)
  report$columns <- list("wrong")
  jsonlite::write_json(report, path, auto_unbox = TRUE)
  expect_error(load_result(result$output_dir), class = "autoschema_invalid_result")
  writeLines(original, path)
  unlink(result$database_path)
  expect_error(load_result(result$output_dir), class = "autoschema_invalid_result")
})

test_that("base R plots and self-contained report are available", {
  result <- convert_dataframe(fixture(), new_output())
  pdf <- tempfile(fileext = ".pdf"); withr::defer(unlink(pdf))
  grDevices::pdf(pdf)
  tryCatch({
    expect_type(plot(result), "double")
    expect_type(plot(result, type = "timings"), "double")
    expect_error(plot(result, type = "bytes"), "CSV")
  }, finally = grDevices::dev.off())
  expect_gt(file.info(pdf)$size, 0)
  html <- paste(readLines(result$report_path, encoding = "UTF-8"), collapse = "\n")
  expect_match(html, "Exact reconstruction verified", fixed = TRUE)
  expect_match(html, "Column statistics", fixed = TRUE)
  expect_match(html, "schema.json", fixed = TRUE)
  expect_false(grepl('<script[^>]+src=|https?://', html))
})
